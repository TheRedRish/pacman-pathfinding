export function registerCustomMaps(customMaps = []) {
    customMaps.forEach((map) => {
        if (!map?.name || !Array.isArray(map.data)) return;

        const key = map.id ? `custom-${map.id}` : map.name.toLowerCase().replace(/\s+/g, "-");
        MAPS[key] = {
            name: map.name,
            width: map.width,
            height: map.height,
            pacman: map.pacman,
            ghosts: map.ghosts,
            data: map.data
        };
    });
}