function createOpenArena() {
    const width = 25;
    const height = 25;

    const data = Array(height).fill(0).map((_, y) =>
        Array(width).fill(0).map((_, x) => {
            if (y === 0 || y === height - 1 || x === 0 || x === width - 1) return 1;
            if (x === 12 && y > 5 && y < 19) return 1;
            if (y === 12 && (x < 5 || x > 19)) return 1;
            return 0;
        })
    );

    return {
        name: "Open Arena",
        width,
        height,
        pacman: { x: 12, y: 12 },
        ghosts: [
            { id: 1, x: 2, y: 2, algorithm: "BFS", color: "#ff0000", name: "Blinky" },
            { id: 2, x: 22, y: 2, algorithm: "DFS", color: "#ffb8ff", name: "Pinky" },
            { id: 3, x: 2, y: 22, algorithm: "Dijkstra", color: "#00ffff", name: "Inky" },
            { id: 4, x: 22, y: 22, algorithm: "A*", color: "#ffb852", name: "Clyde" }
        ],
        data
    };
}

function createDenseMaze() {
    const width = 30;
    const height = 30;

    const data = Array(height).fill(0).map((_, y) =>
        Array(width).fill(0).map((_, x) => {
            if (y === 0 || y === height - 1 || x === 0 || x === width - 1) return 1;
            if ((x % 4 === 0 || y % 4 === 0) && Math.random() > 0.3) return 1;
            return 0;
        })
    );

    return {
        name: "Dense Maze",
        width,
        height,
        pacman: { x: 15, y: 15 },
        ghosts: [
            { id: 1, x: 2, y: 2, algorithm: "BFS", color: "#ff0000", name: "Blinky" },
            { id: 2, x: 27, y: 2, algorithm: "DFS", color: "#ffb8ff", name: "Pinky" },
            { id: 3, x: 2, y: 27, algorithm: "Dijkstra", color: "#00ffff", name: "Inky" },
            { id: 4, x: 27, y: 27, algorithm: "A*", color: "#ffb852", name: "Clyde" }
        ],
        data
    };
}

